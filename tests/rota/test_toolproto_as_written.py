# Forms that Python reads as written, and that the rewrites read otherwise.
# Each one now gets Python's value.
@pytest.mark.parametrize("args, want", [
    ("body=r'''a\nb'''", {"body": "a\nb"}),
    ("body='a\\\nb'", {"body": "ab"}),
    ("a=1,  # a note\nb=2", {"a": 1, "b": 2}),
])
def test_a_list_python_reads_keeps_python_s_value(args, want):
    assert toolproto.parse_args(args)[0] == want


# The cases the rewrites were built for still reach them.
@pytest.mark.parametrize("args, want", [
    ("result=pass", {"result": "pass"}),
    ("note='a\nb'", {"note": "a\nb"}),
    ("a='x',\nresult=pass", {"a": "x", "result": "pass"}),
])
def test_a_list_python_refuses_still_gets_the_rewrites(args, want):
    assert toolproto.parse_args(args)[0] == want
